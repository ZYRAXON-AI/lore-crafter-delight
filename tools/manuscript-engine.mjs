  return `${pick(p.light, seed + 18)}-এ সব কিছু আবার স্থির হয়। ${book.place}-এর ${book.feature} পুরনো চেহারায় ফিরে আসে, আর ${book.protagonist}-এর বুকে ${book.theme} থিতু হয়। কিন্তু শেষে একটা প্রশ্ন বাকি থাকে, যার উত্তর হয়তো পরের গল্পে।`;
