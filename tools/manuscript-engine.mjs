export function paragraphSet(book, chapterIndex) {
  const p = PALETTES[book.genre] ?? PALETTES["প্রেম"];
  const seed = book.id * 13 + chapterIndex * 7;
  const beat = BEATS[chapterIndex] ?? BEATS[BEATS.length - 1];
  const paras = [
    atmosphere(book, p, seed, chapterIndex),
    placeDescription(book, p, seed),
    inner(book, p, seed, beat),
    companion(book, seed),
    memory(book, p, seed),
    motif(book, p, seed),
    sensory(book, p, seed),
    dialogue(book, seed),
    escalation(book, p, seed),
    action(book, p, seed),
    revelation(book, seed, beat),
  ];
  if (chapterIndex >= BEATS.length - 2) paras.push(resolve(book, p, seed));
  paras.push(cliff(book, seed));
  // Twelve further paragraphs lift each chapter from a short scene to a
  // novel-like chapter; the deeper set then pushes it to roughly fifteen to
  // twenty printed pages. Both sets are rotated by chapter so the longer
  // chapters do not open on the same beat as their neighbour.
  const extra = extraParagraphs(book, p, pick, seed);
  const deeper = deeperParagraphs(book, p, pick, seed);
  const rotate = (list) => {
    const at = (chapterIndex * 5) % list.length;
    return [...list.slice(at), ...list.slice(0, at)];
  };
  return [...paras, ...rotate(extra), ...rotate(deeper)];
}

export function buildBook(profile, openingParagraphs) {
  const chapters = BEATS.map((_, index) => {
    const paragraphs =
      index === 0 && openingParagraphs?.length
        ? [...openingParagraphs, ...paragraphSet(profile, 0).slice(1)]
        : paragraphSet(profile, index);
    return { title: profile.outline[index] ?? `অধ্যায় ${bn(index + 1)}`, paragraphs };
  });
  return {
    id: profile.id,
    title: profile.title,
    genre: profile.genre,
    subtitle: profile.subtitle,
    outline: profile.outline,
    chapters,
  };
}

